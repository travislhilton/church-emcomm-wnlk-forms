#!/usr/bin/env python3
"""Generate the Winlink Express *display* forms (``*_Viewer.html``) from the three
Initial templates.

    python installer/make-viewers.py        (run from the repo root after editing an Initial form)

How Winlink uses them: each ``.txt`` template definition names the pair
``Form:<Initial>.html,<Viewer>.html``.  When the sender submits the Initial form,
Winlink Express attaches ``RMS_Express_Form_<Viewer>.xml`` (every posted field) to
the message.  When the recipient opens that message in Winlink Express, it fills
every ``{var name}`` placeholder in the viewer from the XML and opens the viewer
in the browser -- the received report looks like the form, not like a text file.
The plain-text body of the message is unchanged, so an AWSRM reading it as
ordinary email, or the EOC Message Center watcher, still gets the full report.

The viewers are committed; this script only regenerates them.
"""
import re
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent / 'templates'

FORMS = [
    # (folder, Initial file, Viewer file, plain-text save name)
    ('disaster-report', 'Church_of_Jesus_Christ_Disaster_Report_Initial.html',
     'Church_of_Jesus_Christ_Disaster_Report_Viewer.html', 'Church_Disaster_Report_received.txt'),
    ('supply-order', 'Church_of_Jesus_Christ_Supply_Order_Initial.html',
     'Church_of_Jesus_Christ_Supply_Order_Viewer.html', 'Church_Supply_Order_received.txt'),
    ('work-crew-log', 'Church_of_Jesus_Christ_Work_Crew_Log.html',
     'Church_of_Jesus_Christ_Work_Crew_Log_Viewer.html', 'Church_Work_Crew_Log_received.txt'),
]

VIEWER_CSS = """.v { display:inline-block; min-width:40px; min-height:14px; border-bottom:1px solid #888; padding:1px 3px; font-size:12px; vertical-align:bottom; }
.v.ta { display:block; white-space:pre-wrap; border:1px solid #999; min-height:28px; padding:3px 5px; width:99%; box-sizing:border-box; }
.rcvd { background:#e8f3e8; border:2px solid #2d8b69; padding:6px 8px; font-size:12px; margin-bottom:6px; }
@media print { details, input[type=button], .rcvd { display:none; } }
"""

VIEWER_SCRIPT = """<script type="text/javascript">
// Winlink Express display form. Winlink fills every {var name} on this page from the
// RMS_Express_Form XML attached to the received message, then opens the page in the browser.
// GENERATED by installer/make-viewers.py from the Initial template -- edit that, then regenerate.

function unvar() {   // blank any {var ...} Winlink could not fill (e.g. a radio button never selected)
  var w = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false), n, list = [];
  while ((n = w.nextNode())) list.push(n);
  for (var i = 0; i < list.length; i++) {
    if (list[i].nodeValue.indexOf('{var') > -1) list[i].nodeValue = list[i].nodeValue.replace(/\\{var\\s+[^}]*\\}/g, '');
  }
}
function txt(id) { var e = document.getElementById(id); return e ? e.textContent.trim() : ''; }
function hideEmptyRows() {
  // Supply Order: hide catalog rows with no quantity (and section headers left empty);
  // Work Crew Log: hide crew rows with no name. The Disaster Report has no such tables.
  var rows = document.querySelectorAll('table.items tbody tr, table.crew tbody tr'), hdr = null, hdrLive = false;
  for (var i = 0; i < rows.length; i++) {
    var r = rows[i];
    if (r.querySelector('.subsechdr')) {
      if (hdr && !hdrLive) hdr.style.display = 'none';
      hdr = r; hdrLive = false; continue;
    }
    var cells = r.querySelectorAll('.v'), any = false;
    if (!cells.length) continue;
    for (var j = 0; j < cells.length; j++) if (cells[j].textContent.trim() && cells[j].textContent.trim() !== '0') { any = true; break; }
    if (any) hdrLive = true; else r.style.display = 'none';
  }
  if (hdr && !hdrLive) hdr.style.display = 'none';
}
function fixFlags() {
  var ex = document.getElementById('exercise_v'), xb = document.getElementById('exbox');
  if (xb) xb.style.display = (ex && /^(yes|1|true|on)$/i.test(ex.textContent.trim())) ? '' : 'none';
  var sc = document.getElementById('safety_cert_v');
  if (sc) { var v = sc.textContent.trim(); sc.textContent = (v === '1' || /^(true|yes|on)$/i.test(v)) ? 'YES' : 'NOT CONFIRMED'; }
}
function copyText() {
  var t = txt('msg_body_pre'), note = document.getElementById('copy_note');
  function done(ok) { note.textContent = ok ? 'Copied.' : 'Open "Plain text as sent" below, select the text and copy it.'; }
  if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(t).then(function() { done(true); }, function() { done(false); });
  else done(false);
}
function saveText() {
  var t = txt('msg_body_pre'), name = '%SAVENAME%';
  var blob = new Blob([t], {type: 'text/plain'});
  if (window.navigator.msSaveBlob) { window.navigator.msSaveBlob(blob, name); return; }
  var a = document.createElement('a'); a.href = URL.createObjectURL(blob); a.download = name; a.style.display = 'none';
  document.body.appendChild(a); a.click(); document.body.removeChild(a);
}
window.onload = function() { unvar(); fixFlags(); hideEmptyRows(); };
</script>"""

TOOLBAR = """  <!-- VIEWER TOOLBAR (generated) -->
  <tr><td colspan="2" style="background:#f0f0f0; padding:6px;">
    <input type="button" value="Print" onclick="window.print()" />
    &nbsp;
    <input type="button" value="Copy plain text" onclick="copyText()" />
    &nbsp;
    <input type="button" value="Save plain text (.txt)" onclick="saveText()" />
    &nbsp;<span id="copy_note" style="font-size:11px; color:#1a6b3c;"></span>
    <br/><small style="color:#555;">&#9432; View-only copy of the form as submitted. The same report is the text of the Winlink message, and the EOC (Emergency Operations Center) Message Center ingests it from Winlink automatically.</small>
  </td></tr>
  <tr><td colspan="2" style="padding:0;">
    <details><summary style="padding:5px 6px; font-size:11px; cursor:pointer;">Plain text as sent</summary>
    <pre id="msg_body_pre" style="font-size:11px; margin:0; padding:6px; white-space:pre-wrap; border-top:1px solid #999;">{var msg_body}</pre></details>
  </td></tr>
"""

RCVD_BANNER = """<div class="rcvd">&#9993; <b>Received via Winlink</b> from <b>{var testCall}</b> &mdash; operator {var op_name} {var op_position}</div>
"""


def sub1(t, pat, rep, flags=0, n=1):
    new, c = re.subn(pat, rep, t, flags=flags)
    if c != n:
        raise SystemExit(f'expected {n} match(es) for {pat!r}, got {c}')
    return new


def make_viewer(src: str, savename: str) -> str:
    t = src
    t = sub1(t, r'<title>(.*?)</title>', lambda m: f'<title>{m.group(1)} (received)</title>')
    t = sub1(t, r'<script type="text/javascript">.*?</script>', lambda m: VIEWER_SCRIPT.replace('%SAVENAME%', savename), flags=re.S)
    t = sub1(t, r'</style>', lambda m: VIEWER_CSS + '</style>')
    t = sub1(t, r'<form id="myform".*?">', lambda m: '<div id="myform">\n' + RCVD_BANNER, flags=re.S)
    t = sub1(t, r'</form>', '</div>')
    t = sub1(t, r'<div id="loc_src_note" class="lbl" style="font-style:italic;"></div>\s*<input type="hidden" id="loc_src" name="loc_src" value="" />',
             '<div class="lbl" style="font-style:italic;">Source: {var loc_src}</div>')
    t = re.sub(r'[ \t]*<input type="hidden"[^>]*/>\r?\n', '', t)
    t = re.sub(r'<label><input type="radio" name="([a-z_]+)" value="YES" /> Yes</label> &nbsp;\s*'
               r'<label><input type="radio" name="\1" value="NO" /> No</label>',
               r'<span class="v">{var \1}</span>', t)
    t = sub1(t, r'<label><input type="checkbox" id="exercise" name="exercise" value="YES" onchange="exChanged\(\)" /> THIS IS AN EXERCISE</label> <small>[^<]*</small>',
             '<span id="exercise_v" style="display:none">{var exercise}</span>&#9888; THIS IS AN EXERCISE &mdash; the sender marked this report as a drill, test or training message')
    t = re.sub(r'<input type="checkbox" id="safety_cert" name="safety_cert" value="1" />',
               '<span class="v" id="safety_cert_v">{var safety_cert}</span>', t)
    t = re.sub(r'<input type="(?:text|tel|email|date)"[^>]*?\bid="([A-Za-z0-9_]+)"[^>]*?/>',
               r'<span class="v" id="v_\1">{var \1}</span>', t)
    t = re.sub(r'<textarea id="([A-Za-z0-9_]+)"[^>]*></textarea>', r'<div class="v ta">{var \1}</div>', t)
    t = sub1(t, r'  <!-- BUTTONS -->.*?(?=\s*</table>\s*</div>)', lambda m: TOOLBAR.rstrip('\n'), flags=re.S)
    for bad in ('{FormServer}', 'type="text"', 'type="date"', 'type="file"', 'type="submit"', '<textarea', 'type="radio"', 'onsubmit', 'type="checkbox"', 'exChanged'):
        if bad in t:
            raise SystemExit(f'viewer still contains {bad!r}')
    return t


def main():
    for folder, initial, viewer, savename in FORMS:
        src = (ROOT / folder / initial).read_text(encoding='utf-8')
        out = make_viewer(src, savename)
        dest = ROOT / folder / viewer
        with open(dest, 'w', encoding='utf-8', newline='\n') as f:
            f.write(out)
        nvars = len(set(re.findall(r'\{var\s+([A-Za-z0-9_]+)\}', out)))
        print(f'{viewer}: {len(out)} bytes, {nvars} distinct {{var}} fields')


if __name__ == '__main__':
    main()
